# 所有系统的坐标注册表
_SYSTEM_COORDS: Dict[str, Dict[str, Tuple[float, float]]] = {
	"13Bus": _13BUS_COORDS,
	"13bus": _13BUS_COORDS,
	"34Bus": _34BUS_COORDS,
	"34bus": _34BUS_COORDS,
	"123Bus": _123BUS_COORDS,
	"123bus": _123BUS_COORDS,
}


def load_bus_coordinates(
	system_name: str = "13Bus",
) -> Dict[str, Tuple[float, float]]:
	"""加载指定 IEEE 系统的母线坐标。

	Args:
		system_name: 系统名称，支持 "13Bus", "34Bus", "123Bus"

	Returns:
		{母线名: (x, y)} 坐标字典

	Raises:
		ValueError: 未知的系统名称
	"""
	coords = _SYSTEM_COORDS.get(system_name)
	if coords is None:
		available = sorted(set(
			k for k in _SYSTEM_COORDS if k[0].isupper()
		))
		raise ValueError(
			f"Unknown system: {system_name}. "
			f"Available: {available}"
		)
	return dict(coords)


def get_available_systems() -> list[str]:
	"""获取所有可用系统名称列表。

	Returns:
		系统名称列表（仅大写形式）
	"""
	return sorted(set(k for k in _SYSTEM_COORDS if k[0].isupper()))
