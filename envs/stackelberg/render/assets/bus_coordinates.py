def load_bus_coordinates(
	system_name: str = "13Bus",
) -> Dict[str, Tuple[float, float]]:
	"""加载指定系统的母线坐标。

	Args:
		system_name: 系统名称 ("13Bus", "34Bus", "123Bus")

	Returns:
		{母线名: (x, y)} 坐标字典
	"""
	return SYSTEM_BUS_COORDS.get(system_name, BUS_COORDS_13BUS)


def load_topology_edges(
	system_name: str = "13Bus",
) -> List[Tuple[str, str]]:
	"""加载指定系统的拓扑边列表。

	Args:
		system_name: 系统名称

	Returns:
		[(from_bus, to_bus), ...] 拓扑边列表
	"""
	return SYSTEM_TOPOLOGY_EDGES.get(system_name, TOPOLOGY_EDGES_13BUS)
